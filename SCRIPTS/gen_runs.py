#!/usr/bin/env python3
"""Generate the Genus run scripts for the ISCAS 2027 revision.

The existing flow has no parameter passing, so earlier sweeps were produced by
hand-editing `parameter` defaults -- fine for one sweep, error-prone for 17
runs. This emits, per run, a thin Verilog wrapper that instantiates the DUT
with explicit parameters plus a self-contained Genus script, so nothing is
edited by hand and every configuration is reproducible from this file.

  python3 gen_runs.py            # writes gen/*.v and gen/*.tcl
  bash run_all_genus.sh          # runs all 17 through Genus
"""
import os

HOME = "/home/redhatacademy19/Documents/Siddhant"   # <-- edit if the path moved
OUT  = os.path.join(os.path.dirname(os.path.abspath(__file__)), "gen")

# module -> (source files, port spec).  Port spec entries are
#   (direction, width-expression or None for 1 bit, name)
MODS = {
 "rope_gain_comp": (["rope_gain_comp.v"], [
    ("input","W","x_in"),("input","W","y_in"),
    ("input","3","delta0"),("input","3","delta1"),
    ("output","W","x_out"),("output","W","y_out")]),
 "rope_angle_encoder": (["rope_angle_encoder.v"], [
    ("input","FB+2","theta_res"),("output","N","ud_bits")]),
 "rope_range_reduce": (["rope_angle_encoder.v"], [
    ("input","PW","phase"),("output","2","quadrant"),
    ("output","FB+2","theta_res")]),
 "rope_bfp_norm": (["rope_bfp_norm.v"], [
    ("input","2*D*W","vec_in"),("output","2*D*W","vec_out"),
    ("output","EW","exp_out")]),
 "rope_bfp_denorm": (["rope_bfp_norm.v"], [
    ("input","2*D*W","vec_in"),("input","EW","exp_in"),
    ("output","2*D*W","vec_out")]),
 "rope_mult_pair": (["rope_mult_pair.v"], [
    ("input",None,"clk"),("input",None,"rst"),
    ("input","W","x_even"),("input","W","x_odd"),
    ("input","W","sin_val"),("input","W","cos_val"),
    ("output","W","y_even"),("output","W","y_odd")]),
 "rope_lut_pair": (["rope_lut_pair.v"], [
    ("input",None,"clk"),("input",None,"rst"),
    ("input","W","x_even"),("input","W","x_odd"),
    ("input","ADDR_W+2","angle_index"),
    ("output","W","y_even"),("output","W","y_odd")]),
 "rope_cordic_pair": (["rope_cordic_pair.v","cordic_standard_core.v",
                       "cordic_standard_stage.v"], [
    ("input",None,"clk"),("input",None,"rst"),
    ("input","W","x_even"),("input","W","x_odd"),("input","W","theta"),
    ("output","W","y_even"),("output","W","y_odd")]),
 "rope_binary_ud_pair": (["rope_binary_ud_pair.v","binary_ud_cordic_core.v"], [
    ("input",None,"clk"),("input",None,"rst"),
    ("input","W","x_even"),("input","W","x_odd"),
    ("input","STAGES","ud_bits"),
    ("output","W","y_even"),("output","W","y_odd")]),
 "rope_csd_pair": (["rope_csd_pair.v","csd_ud_cordic_core.v","csd_ud_stage.v",
                    "csd_control.v"], [
    ("input",None,"clk"),("input",None,"rst"),
    ("input","WIDTH","x_in"),("input","WIDTH","y_in"),
    ("input","2*STAGES","angle_bits"),
    ("output","WIDTH","x_out"),("output","WIDTH","y_out")]),
}

# (tag, module, {params}) — mirrors SYNTHESIS_RUN_LIST.md
RUNS = [
 ("01_gaincomp_H1_W12", "rope_gain_comp",      {"W":12,"MODE":1}),
 ("02_gaincomp_H1_W14", "rope_gain_comp",      {"W":14,"MODE":1}),
 ("03_gaincomp_H2_W12", "rope_gain_comp",      {"W":12,"MODE":2}),
 ("04_gaincomp_H2_W14", "rope_gain_comp",      {"W":14,"MODE":2}),
 ("05_angleenc",        "rope_angle_encoder",  {"N":10,"FB":12}),
 ("06_rangered",        "rope_range_reduce",   {"PW":16,"FB":12}),
 ("07_bfpnorm_W12_D64", "rope_bfp_norm",       {"W":12,"D":64,"EW":6}),
 ("08_bfpnorm_W14_D64", "rope_bfp_norm",       {"W":14,"D":64,"EW":6}),
 ("09_bfpdenorm_W14",   "rope_bfp_denorm",     {"W":14,"D":64,"EW":6}),
 ("10_mult_W12",        "rope_mult_pair",      {"W":12}),
 ("11_lut_W12",         "rope_lut_pair",       {"W":12,"ADDR_W":7}),
 ("12_stdcordic_W12",   "rope_cordic_pair",    {"W":12,"STAGES":10}),
 ("13_stdcordic_W14",   "rope_cordic_pair",    {"W":14,"STAGES":10}),
 ("14_binaryud_W12",    "rope_binary_ud_pair", {"W":12,"STAGES":10}),
 ("15_binaryud_W14",    "rope_binary_ud_pair", {"W":14,"STAGES":10}),
 ("16_bfpnorm_W14_D8",  "rope_bfp_norm",       {"W":14,"D":8,"EW":6}),
 ("17_bfpnorm_W14_D16", "rope_bfp_norm",       {"W":14,"D":16,"EW":6}),
]

def width(expr, P):
    return eval(expr, {}, dict(P))

def wrapper(tag, mod, P):
    top = f"top_{tag}"
    decl, conn = [], []
    for d, w, n in MODS[mod][1]:
        if w is None:
            decl.append(f"    {d} {n}")
        else:
            decl.append(f"    {d} [{width(w,P)-1}:0] {n}")
        conn.append(f"        .{n}({n})")
    pars = ",\n".join(f"        .{k}({v})" for k, v in P.items())
    return (f"// generated by gen_runs.py — do not edit\n"
            f"module {top} (\n" + ",\n".join(decl) + "\n);\n"
            f"    {mod} #(\n{pars}\n    ) dut (\n" + ",\n".join(conn) + "\n    );\n"
            f"endmodule\n")

TCL = """# generated by gen_runs.py — Genus run {tag}
# design {mod}  params {parstr}
set DESIGN top_{tag}
set RUNDIR {tag}

set _OUT  OUTPUT/outputs_{tag}
set _REP  OUTPUT/reports_{tag}
file mkdir $_OUT
file mkdir $_REP

set rtlDir  {home}/RTL
set genDir  {home}/SCRIPTS/gen
set libDir [list \\
  {home}/gsclib045_all_v4.8/gsclib045/timing \\
  {home}/gsclib045_all_v4.8/gsclib045_hvt/timing \\
  {home}/gsclib045_all_v4.8/gsclib045_lvt/timing ]
set libList [list \\
  fast_vdd1v2_basicCells.lib \\
  fast_vdd1v2_multibitsDFF.lib \\
  fast_vdd1v2_basicCells_hvt.lib \\
  fast_vdd1v2_basicCells_lvt.lib ]

set_db init_lib_search_path $libDir
set_db init_hdl_search_path $rtlDir
set_db max_cpus_per_server 8
set_db information_level 9
set_db tns_opto true

read_libs $libList
read_physical -lefs {{ \\
  {home}/gsclib045_all_v4.8/gsclib045/lef/gsclib045_tech.lef \\
  {home}/gsclib045_all_v4.8/gsclib045/lef/gsclib045_macro.lef \\
  {home}/gsclib045_all_v4.8/gsclib045/lef/gsclib045_multibitsDFF.lef \\
  {home}/gsclib045_all_v4.8/gsclib045_hvt/lef/gsclib045_hvt_macro.lef \\
  {home}/gsclib045_all_v4.8/gsclib045_lvt/lef/gsclib045_lvt_macro.lef }}
set_db qrc_tech_file {home}/gsclib045_all_v4.8/gsclib045_tech/qrc/qx/gpdk045.tch

read_hdl [list {rtlfiles} $genDir/top_{tag}.v ]
elaborate $DESIGN
set_top_module $DESIGN
read_sdc {home}/CONSTRAINTS/{sdc}
check_design -unresolved

syn_generic
syn_map
syn_opt

report_summary -directory $_REP/$DESIGN/opt
report_power  > $_REP/$DESIGN/opt/power.rpt
report_area   > $_REP/$DESIGN/opt/area.rpt
report_timing > $_REP/$DESIGN/opt/timing.rpt

puts "=== DONE {tag} ==="
puts "AREA:  [get_db [current_design] .area]"
exit
"""

SEQ = {"rope_mult_pair","rope_lut_pair","rope_cordic_pair",
       "rope_binary_ud_pair","rope_csd_pair"}

os.makedirs(OUT, exist_ok=True)
for tag, mod, P in RUNS:
    open(os.path.join(OUT, f"top_{tag}.v"), "w").write(wrapper(tag, mod, P))
    rtl = " ".join(f"$rtlDir/{f}" for f in MODS[mod][0])
    open(os.path.join(OUT, f"run_{tag}.tcl"), "w").write(TCL.format(
        tag=tag, mod=mod, parstr=" ".join(f"{k}={v}" for k,v in P.items()),
        home=HOME, rtlfiles=rtl,
        sdc="rope.sdc" if mod in SEQ else "original_rope.sdc"))
    print(f"  {tag:<22} {mod:<20} " + " ".join(f"{k}={v}" for k,v in P.items()))
print(f"\n{len(RUNS)} runs written to {OUT}/")
